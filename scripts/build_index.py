#!/usr/bin/env python3
"""
build_index.py
Purpose:      Rebuild every recipe index from the files in the repository.
Requirements: Python 3.8+ (standard library only)
Usage:        python scripts/build_index.py
Updates:      README.md (categories and recipes), CONTRIBUTING.md (file tree),
              and an index README.md inside each section folder.
How it works: Each recipe needs a "Purpose:" line near the top. Markdown recipes
              use their first "# Title" heading as the display name.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {".git", ".github", "assets", "scripts", "node_modules", "__pycache__"}
SKIP_TREE = {".git", "node_modules", "__pycache__"}
RECIPE_EXTS = {".md", ".txt", ".js", ".py", ".sh", ".json"}
AUTO = "<!-- AUTO-GENERATED by scripts/build_index.py. Edit the recipes, not this file. -->"

# folder name -> (title, description, badge logo, badge color)
SECTIONS = {
    "social-media": ("Social Media", "Platform-by-platform tips for YouTube, Instagram, Facebook, X, TikTok, WhatsApp, Reddit, and LinkedIn", "youtube", "ef4444"),
    "browsers": ("Browsers and Search", "Shortcuts, settings, and search tricks for Chrome, Firefox, and web search", "googlechrome", "2563eb"),
    "privacy-and-security": ("Privacy and Security", "Accounts, passwords, email aliases, tracking removal, and scam spotting", "protonmail", "7c3aed"),
    "developer": ("Developer", "DevTools, automation scripts, API and webhook recipes, Git and GitHub", "github", "64748b"),
    "everyday": ("Everyday", "Windows shortcuts, maps, and savings tips", "googlemaps", "22c55e"),
}
SUBFOLDERS = {
    "x-twitter": "X (Twitter)", "tiktok": "TikTok", "youtube": "YouTube",
    "linkedin": "LinkedIn", "whatsapp": "WhatsApp", "devtools": "DevTools",
    "api-and-webhooks": "API and Webhooks", "git-and-github": "Git and GitHub",
    "automation": "Automation and Scraping",
}


def humanize(name):
    return SUBFOLDERS.get(name, name.replace("-", " ").replace("_", " ").title())


def section_info(name):
    return SECTIONS.get(name, (humanize(name), "", "readme", "64748b"))


def read_head(path, lines=25):
    try:
        with open(path, encoding="utf-8") as f:
            return "".join(next(f, "") for _ in range(lines))
    except (OSError, UnicodeDecodeError):
        return ""


PURPOSE = re.compile(r"(?:\*\*)?Purpose:(?:\*\*)?\s*(.+)")
JSON_PURPOSE = re.compile(r'"_purpose"\s*:\s*"(.+?)"')


def describe(path):
    head = read_head(path)
    m = (JSON_PURPOSE if path.suffix == ".json" else PURPOSE).search(head)
    return m.group(1).strip().replace("|", "\\|") if m else ""


def title_of(path):
    if path.suffix == ".md":
        m = re.search(r"^#\s+(.+)$", read_head(path, 5), re.M)
        if m:
            return m.group(1).strip()
    return path.stem.replace("-", " ").replace("_", " ").title()


def collect():
    sections = [p for p in ROOT.iterdir()
                if p.is_dir() and p.name not in SKIP_DIRS and not p.name.startswith(".")]
    order = {name: i for i, name in enumerate(SECTIONS)}
    sections.sort(key=lambda p: (order.get(p.name, 999), p.name))
    data = {}
    for sec in sections:
        subs = {}
        for f in sorted(sec.rglob("*")):
            if not f.is_file() or f.suffix not in RECIPE_EXTS or f.name == "README.md":
                continue
            rel = f.relative_to(sec)
            sub = rel.parts[0] if len(rel.parts) > 1 else ""
            subs.setdefault(sub, []).append(f)
        if subs:
            data[sec.name] = dict(sorted(subs.items(), key=lambda kv: (kv[0] != "", humanize(kv[0]))))
    return data


def sub_label(sub):
    return humanize(sub) if sub else "General"


def table(files, base):
    lines = ["| Recipe | Description |", "|---|---|"]
    for f in files:
        link = f.relative_to(base).as_posix()
        lines.append(f"| [{title_of(f)}]({link}) | {describe(f)} |")
    return "\n".join(lines)


def section_index(sec, subs):
    label, blurb, _, _ = section_info(sec)
    out = [AUTO, "", f"# {label}", ""]
    if blurb:
        out += [blurb + ".", ""]
    for sub, files in subs.items():
        out += [f"## {sub_label(sub)}", "", table(files, ROOT / sec), ""]
    out += ["---", "", "[Back to main README](../README.md) | [How to add a trick](../CONTRIBUTING.md)", ""]
    return "\n".join(out)


def readme_blocks(data):
    cats = ["| | Section | What it covers | Recipes |", "|:-:|---|---|:-:|"]
    blocks = []
    for sec, subs in data.items():
        label, blurb, logo, color = section_info(sec)
        n = sum(len(v) for v in subs.values())
        badge = f"![](https://img.shields.io/badge/-%20-{color}?style=flat-square&logo={logo}&logoColor=white)"
        cats.append(f"| {badge} | [**{label}**]({sec}) | {blurb} | {n} |")
        b = ["<details>", f"<summary><b>{label}</b> ({n} recipes)</summary>", "", "<br>", "",
             f"[Open the {label} index]({sec}/README.md)", ""]
        for sub, files in subs.items():
            b += [f"**{sub_label(sub)}**", "", table(files, ROOT), ""]
        b += ["</details>", ""]
        blocks.append("\n".join(b))
    return "\n".join(cats), "\n".join(blocks).rstrip()


def tree(path=ROOT, prefix=""):
    entries = [p for p in path.iterdir() if p.name not in SKIP_TREE]
    entries.sort(key=lambda p: (p.is_file(), p.name.lower()))
    lines = []
    for i, p in enumerate(entries):
        last = i == len(entries) - 1
        lines.append(prefix + ("`-- " if last else "|-- ") + p.name + ("/" if p.is_dir() else ""))
        if p.is_dir():
            lines += tree(p, prefix + ("    " if last else "|   "))
    return lines


def inject(path, name, content):
    if not path.exists():
        print(f"skipped {path.name} (not found)")
        return
    start, end = f"<!-- {name}:START -->", f"<!-- {name}:END -->"
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        print(f"warning: {name} markers not found in {path.name}")
        return
    new = pattern.sub(lambda m: f"{start}\n{content}\n{end}", text)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    data = collect()
    for sec, subs in data.items():
        write(ROOT / sec / "README.md", section_index(sec, subs))
    cats, recipes = readme_blocks(data)
    inject(ROOT / "README.md", "CATEGORIES", cats)
    inject(ROOT / "README.md", "RECIPES", recipes)
    tree_text = "```text\ninternet-tricks-cookbook/\n" + "\n".join(tree()) + "\n```"
    inject(ROOT / "CONTRIBUTING.md", "TREE", tree_text)
    total = sum(len(f) for s in data.values() for f in s.values())
    missing = [f.relative_to(ROOT).as_posix() for s in data.values() for fl in s.values() for f in fl if not describe(f)]
    print(f"Indexed {total} recipes in {len(data)} sections.")
    if missing:
        print("Missing a 'Purpose:' line in:")
        for m in missing:
            print("  " + m)


if __name__ == "__main__":
    main()
